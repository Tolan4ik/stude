package main

import "fmt"

// Объявляем функцию exchange, которая принимает сумму в рублях (rub типа int)
// и возвращает строку (string) с названием подходящего тарифного пакета.
func exchange(rub int) string {
	// Используем switch без выражения, чтобы гибко проверять диапазоны чисел.
	switch {
	// Категория 1: Если сумма строго меньше 1000 рублей.
	case rub < 1000:
		// Возвращаем базовый пакет. Оператор return сразу завершает работу функции.
		return "Пакет: Базовый (высокая комиссия)"

	// Категория 2: Если сумма от 1000 до 10000 рублей включительно.
	// Оператор && означает логическое "И" (должны выполняться оба условия одновременно).
	case rub >= 1000 && rub <= 10000:
		return "Пакет: Серебряный (стандартная комиссия)"

	// Категория 3: Сработает во всех остальных случаях (когда сумма строго больше 10000).
	default:
		return "Пакет: Золотой (без комиссии!)"
	}
}

func main() {
	// Пример вызова функции: сумма 5000 рублей попадает в "Серебряный" пакет
	fmt.Println(exchange(5000))
}
