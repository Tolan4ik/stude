package main

import "fmt"

func main() {
	// Создаем срез (slice) целых чисел со значениями от 10 до 70.
	// В отличие от массивов, размер среза не указывается в квадратных скобках.
	numbers := []int{10, 20, 30, 40, 50, 60, 70}

	// Функция len() возвращает количество элементов в срезе.
	// В данном случае total будет равен 7.
	total := len(numbers)

	// Проверяем условие: действительно ли 7 > 5?
	// В Go вокруг условия оператора if круглые скобки () писать НЕ нужно.
	if total > 5 {
		// Спецификатор %d подставит значение переменной total (число 7) внутрь строки.
		fmt.Printf("В срезе много элементов! Их там: %d", total)
	}
}
