package main

import "fmt"

func main() {
	// Создаем строку. В Go строки хранятся как последовательности байт в кодировке UTF-8.
	// Буквы кириллицы (например, "П", "р" и т.д.) в UTF-8 занимают по 2 байта каждая.
	s := "Привет"

	// Цикл for range при обходе строки итерирует её не по байтам, а по рунам (символам Unicode).
	// i — это индекс БАЙТА, с которого начинается текущая руна.
	// r — это сама руна (тип данных rune, который является синонимом int32).
	for i, r := range s {
		// %d выводит индекс начального байта символа (0, 2, 4, 6, 8, 10).
		// %c выводит руну как печатный символ (П, р, и, в, е, т).
		fmt.Printf("%d %c\n", i, r)
	}
}
