package main

import (
	"fmt"
	"unicode/utf8"
)

func main() {
	s := "Привет"

	// Превращаем строку в срез (slice) рун.
	// Go выделяет новую память и копирует туда символы Unicode по отдельности.
	runes := []rune(s)

	// Берем первую руну, приводим её обратно к строке и выводим: "П"
	fmt.Println(string(runes[0])) // "П"

	// len() от среза рун возвращает количество ЭЛЕМЕНТОВ (символов): 6
	fmt.Println(len(runes)) // 6 символов

	// Спецификатор %c выводит руну напрямую как печатный символ, без явного string()
	fmt.Printf("%c\n", runes[0])

	// Функция из пакета utf8 считает символы напрямую в строке, не создавая срез рун
	fmt.Println(utf8.RuneCountInString(s))

	// Обратные кавычки (сырой литерал) позволяют писать многострочный текст
	// со всеми переносами строк и табуляциями, как они есть в коде
	fmt.Print(`hi
	bye
	`)

	// Срезы рун изменяемы. Мы меняем первую руну 'П' на 'Ы' (кавычки одинарные для рун)
	runes[0] = 'Ы'
	// Собираем из измененного среза рун новую строку и перезаписываем переменную s
	s = string(runes)
	fmt.Println(s) // Выведет: "Ыривет"

	hi := "hellllo"
	// Строки из латиницы (ASCII) занимают по 1 байту на символ.
	// Переводим строку в срез байт. Это тоже создает копию данных в памяти.
	he := []byte(hi)
	// Меняем первый байт 'h' на 'H'
	he[0] = 'H'
	// Собираем новую строку из измененного среза байт
	hi = string(he)
	fmt.Println(hi) // Выведет: "Hellllo"

	// Переменные без явной инициализации всегда получают "нулевое значение" (zero value)
	var ok bool
	fmt.Println(ok) // Для bool нулевое значение — это false

	var n int
	var o string
	fmt.Println(n) // Для чисел нулевое значение — это 0
	fmt.Println(o) // Для строк нулевое значение — это пустая строка ""
}
